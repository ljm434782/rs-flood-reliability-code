"""Render manuscript LaTeX tables from the locked formal summary CSV files."""

import csv
from pathlib import Path



ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "outputs" / "formal_v1" / "summary_tables"
TARGET = ROOT / "paper" / "tables"
MODELS = ("B1", "B2", "B4", "B5", "P")


def read(name):
    with (SOURCE / name).open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def fmt(value):
    return f"{float(value):.3f}"


def ci(row, key):
    return (f"{fmt(row[key])} "
            f"[{fmt(row[key + '_ci_low'])}, {fmt(row[key + '_ci_high'])}]")


def table(name, header, rows, caption, label, columns):
    lines = ["% Generated by scripts/build_paper_tables.py from frozen result summaries.",
             "\\begin{table}[H]", "\\centering", "\\small",
             "\\setlength{\\tabcolsep}{5pt}", "\\renewcommand{\\arraystretch}{1.15}",
             f"\\caption{{{caption}}}",
             f"\\label{{{label}}}",
             f"\\begin{{tabular}}{{{columns}}}",
             "\\toprule",
             header.rstrip(" \\") + r" \\", "\\midrule"]
    lines.extend(row + r" \\" for row in rows)
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}", ""])
    (TARGET / name).write_text("\n".join(lines), encoding="utf-8")


def main():
    TARGET.mkdir(parents=True, exist_ok=True)
    primary = {row["model"]: row for row in read("primary_metrics.csv")}
    table("primary.tex", "Model & Internal flood IoU & Holdout flood IoU & External water IoU \\",
          [f"{model} & {ci(primary[model], 'internal_flood_iou')} & "
           f"{ci(primary[model], 'holdout_flood_iou')} & "
           f"{ci(primary[model], 'external_water_iou')}" for model in MODELS],
          "Process-equal mean IoU and 95\\% process bootstrap intervals. Internal and "
          "official holdout use three-class flood IoU (19 and 8 processes); the "
          "Sen1Floods11 column uses binary water IoU on 8 independently eligible events.",
          "tab:primary", "lccc")
    curve = {(row["model"], int(row["s2_block_retention_pct"])): row
             for row in read("optical_retention_curve.csv")}
    table("retention.tex", "Model & 100\\% & 75\\% & 50\\% & 25\\% & 0\\% \\",
          [model + " & " + " & ".join(fmt(curve[model, level]["flood_iou"])
                                       for level in (100, 75, 50, 25, 0))
           for model in MODELS],
          "Internal-test flood IoU on the same 19 processes under nested 32$\\times$32 "
          "optical block retention. The source optical validity mask remains in force.",
          "tab:retention", "lccccc")
    calibration = {(row["model"], row["metric"]): row
                   for row in read("calibration_metrics.csv")}
    table("calibration.tex", "Model & $T$ & NLL raw & NLL scaled & ECE raw & ECE scaled \\",
          [f"{model} & {fmt(calibration[model, 'nll']['temperature'])} & "
           f"{fmt(calibration[model, 'nll']['raw'])} & "
           f"{fmt(calibration[model, 'nll']['calibrated'])} & "
           f"{fmt(calibration[model, 'ece15']['raw'])} & "
           f"{fmt(calibration[model, 'ece15']['calibrated'])}"
           for model in MODELS if model != "B1"],
          "Internal-test probability metrics at 100\\% optical retention. One global "
          "temperature per neural model was fitted only on calibration processes; "
          "ECE uses 15 fixed bins.", "tab:calibration", "lccccc")
    missing = {row["model"]: row for row in read("real_missing_s2.csv")
               if row["category"] == "all_unqualified"}
    table("real_missing.tex", "Model & Flood IoU & Macro IoU \\",
          [f"{model} & {ci(missing[model], 'flood_iou')} & "
           f"{fmt(missing[model]['macro_iou'])}" for model in MODELS],
          "Actual internal-test S1 tiles lacking an S2 that passes the frozen "
          "30-day and 50\\% visibility rules (651 tiles, 15 processes).",
          "tab:realmissing", "lcc")
    print(f"Saved 4 manuscript tables to {TARGET}")


if __name__ == "__main__":
    main()
