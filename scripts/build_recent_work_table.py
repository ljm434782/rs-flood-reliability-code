"""Render an editorial literature comparison using existing verified BibTeX entries.

This table describes prior work; it contains no newly calculated experiment scores.
The final column states this manuscript's scope, not an exhaustive absence claim.
"""

import csv
import re
from pathlib import Path



ROOT = Path(__file__).resolve().parents[1]


def latex(text):
    escapes = {"&": r"\&", "%": r"\%", "_": r"\_", "#": r"\#"}
    return "".join(escapes.get(char, char) for char in text)


def main():
    source = ROOT / "paper/data/recent_work.csv"
    bib = (ROOT / "literature/references.bib").read_text(encoding="utf-8")
    with source.open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    if not 5 <= len(rows) <= 6:
        raise ValueError("Expected five or six recent-work rows.")
    for row in rows:
        entry = re.search(r"@\w+\{" + re.escape(row["citation_key"]) +
                          r",(.*?)(?=\n@|\Z)", bib, flags=re.S)
        if entry is None or not re.search(
                r"\byear\s*=\s*\{" + re.escape(row["year"]) + r"\}", entry[1]):
            raise ValueError(f"Missing citation or mismatched year: {row['citation_key']}")
        if not 2024 <= int(row["year"]) <= 2026 or not row["verified_source"].startswith("https://"):
            raise ValueError("A recent year and a verified source URL are required.")
    lines = [
        "% Generated by scripts/build_recent_work_table.py from paper/data/recent_work.csv.",
        r"\begin{table}[H]", r"\centering", r"\footnotesize",
        r"\caption{Selected related work from 2024--2026. The final column states this "
        r"study's relationship and scope; it does not claim an exhaustive research gap "
        r"or comparable performance across datasets.}",
        r"\label{tab:recentwork}", r"\setlength{\tabcolsep}{3pt}",
        r"\renewcommand{\arraystretch}{1.15}",
        r"\begin{tabular}{>{\raggedright\arraybackslash}p{0.17\linewidth}"
        r">{\raggedright\arraybackslash}p{0.21\linewidth}"
        r">{\raggedright\arraybackslash}p{0.26\linewidth}"
        r">{\raggedright\arraybackslash}p{0.30\linewidth}}",
        r"\toprule", r"Study / year & Data or task & Reported achievement & Relationship to this study \\",
        r"\midrule",
    ]
    for row in rows:
        first = latex(row["study"]) + " (" + row["year"] + r") \citep{" + row["citation_key"] + "}"
        lines.append(" & ".join([first] + [latex(row[key]) for key in ("task", "achievement", "relation")]) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    target = ROOT / "paper/tables/recent_work.tex"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines), encoding="utf-8")
    print(target)


if __name__ == "__main__":
    main()
